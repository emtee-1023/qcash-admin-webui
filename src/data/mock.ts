export type BusinessStatus = 'pending' | 'active' | 'suspended' | 'closed'
export type KycStatus = 'unverified' | 'pending' | 'verified' | 'rejected'
export type UserStatus = 'active' | 'suspended'
export type OwnerRole = 'Owner' | 'Manager' | 'Staff'

export interface BusinessOwner {
  id: number
  userId: number
  name: string
  email: string
  phone: string
  role: OwnerRole
  isPrimary: boolean
  status: 'active' | 'suspended'
}

export interface PaymentAccount {
  id: number
  provider: string
  channelType: 'Paybill' | 'Till'
  accountReference: string
  accountName: string
  status: 'active' | 'pending' | 'inactive'
  verifiedAt: string | null
}

export interface Business {
  id: number
  publicId: string
  name: string
  businessType: string
  businessCategory: string
  registrationNumber: string | null
  phone: string
  email: string
  hasPhysicalLocation: boolean
  county: string
  town: string
  ward: string
  physicalAddress: string | null
  operatingSince: string
  status: BusinessStatus
  kycStatus: KycStatus
  collectionAccount: string | null
  paybillNumber: string | null
  walletBalanceMinor: number
  monthlyInflowMinor: number
  advancesOutstandingMinor: number
  createdAt: string
  owners: BusinessOwner[]
  paymentAccounts: PaymentAccount[]
}

export interface AdminUser {
  id: number
  name: string
  email: string | null
  phone: string
  idType: 'Kenyan National ID' | 'Passport'
  identificationNumber: string
  dateOfBirth: string
  isAdmin: boolean
  adminActivatedAt: string | null
  role: 'Super admin' | 'Admin' | 'Customer'
  businessesCount: number
  createdAt: string
  lastActiveAt: string
  status: UserStatus
}

export interface NotificationItem {
  id: number
  title: string
  description: string
  category: 'kyc' | 'business' | 'user' | 'system'
  time: string
  read: boolean
}

export interface ActivityItem {
  id: number
  actor: string
  action: string
  target: string
  meta: string
  time: string
  tone: 'green' | 'blue' | 'purple' | 'amber' | 'orange' | 'red'
}

